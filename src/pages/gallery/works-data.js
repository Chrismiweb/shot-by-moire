export function getWorksByCategorySlug(slug) {
  return works
    .filter((w) => slugify(w.category) === slug)
    .flatMap((work) => {
      // If the work has multiple images, create one gallery item per image
      if (work.images && work.images.length > 0) {
        return work.images.map((image, index) => ({
          ...work,
          id: `${work.id}-${index}`,
          image,
        }));
      }

      // Normal work with only one image
      return [
        {
          ...work,
          image: work.image,
        },
      ];
    });
}