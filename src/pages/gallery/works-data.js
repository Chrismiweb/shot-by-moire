/** Turn a category name into a URL-safe slug, e.g. "New Year" -> "new-year" */
export function slugify(str) {
  return str.toLowerCase().trim().replace(/\s+/g, "-");
}

/** Unique list of category names, in first-seen order. */
export function getCategories() {
  return [...new Set(works.map((w) => w.category))];
}

